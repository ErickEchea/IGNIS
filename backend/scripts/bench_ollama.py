"""Benchmark local Ollama models one at a time (never both loaded together).

Measures, per model: load time, VRAM and system RAM while loaded (nvidia-smi / psutil-free fallback),
latency and generation speed for short and long contexts, JSON-mode validity, and stability over
repeated runs. Writes docs/hardware_report.md.

Usage: uv run python scripts/bench_ollama.py qwen3:8b llama3.1:8b
"""

from __future__ import annotations

import json
import statistics
import subprocess
import sys
import time
from pathlib import Path

import httpx

BASE = "http://127.0.0.1:11434"
REPO = Path(__file__).resolve().parents[2]
FILLER = (
    "Flame spread over thin solids in low gravity depends on the oxidizer flow velocity, the oxygen "
    "concentration and the total pressure. "
)
SCHEMA = {
    "type": "object",
    "properties": {"answer": {"type": "string"}, "citations": {"type": "array", "items": {"type": "string"}}},
    "required": ["answer", "citations"],
}


def gpu_mem_mib() -> int | None:
    try:
        out = subprocess.run(
            ["nvidia-smi", "--query-gpu=memory.used", "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=10, check=True,
        ).stdout
        return int(out.strip().splitlines()[0])
    except (OSError, subprocess.SubprocessError, ValueError):
        return None


def ollama_ps() -> list[dict[str, object]]:
    r = httpx.get(f"{BASE}/api/ps", timeout=5)
    return list(r.json().get("models", []))


def unload(model: str) -> None:
    httpx.post(f"{BASE}/api/generate", json={"model": model, "keep_alive": 0}, timeout=60)
    time.sleep(3)


def chat(model: str, prompt: str, num_ctx: int, json_mode: bool) -> dict[str, object]:
    payload: dict[str, object] = {
        "model": model, "stream": False, "think": False,
        "messages": [{"role": "user", "content": prompt}],
        "options": {"temperature": 0.1, "num_ctx": num_ctx, "num_predict": 160},
        "keep_alive": "5m",
    }
    if json_mode:
        payload["format"] = SCHEMA
    t0 = time.time()
    r = httpx.post(f"{BASE}/api/chat", json=payload, timeout=600)
    r.raise_for_status()
    d = r.json()
    wall = time.time() - t0
    ev = d.get("eval_count", 0) or 0
    ev_s = (d.get("eval_duration", 0) or 0) / 1e9
    ok_json = None
    if json_mode:
        try:
            ok_json = isinstance(json.loads(d["message"]["content"]), dict)
        except (KeyError, ValueError):
            ok_json = False
    return {
        "wall_s": round(wall, 2),
        "load_s": round((d.get("load_duration", 0) or 0) / 1e9, 2),
        "prompt_tokens": d.get("prompt_eval_count", 0),
        "gen_tokens": ev,
        "tok_per_s": round(ev / ev_s, 1) if ev_s else None,
        "json_ok": ok_json,
    }


def bench(model: str) -> dict[str, object]:
    for m in ollama_ps():
        unload(str(m.get("name")))
    base_vram = gpu_mem_mib()
    first = chat(model, "Reply with the word ready.", 2048, False)
    loaded = ollama_ps()
    info = next((m for m in loaded if m.get("name") == model), {})
    vram = gpu_mem_mib()
    runs = []
    for ctx_words, num_ctx in ((200, 4096), (2500, 8192), (5500, 16384)):
        prompt = (FILLER * (ctx_words // 20)) + (
            "\nUsing only the text above, return JSON with a one-sentence answer to: "
            "what does flame spread depend on? Put 'S1' in citations."
        )
        for _ in range(3):
            res = chat(model, prompt, num_ctx, True)
            res["num_ctx"] = num_ctx
            runs.append(res)
    unload(model)
    by_ctx: dict[int, list[dict[str, object]]] = {}
    for r in runs:
        by_ctx.setdefault(int(r["num_ctx"]), []).append(r)  # type: ignore[call-overload]
    summary = {}
    for ctx, rs in by_ctx.items():
        summary[ctx] = {
            "median_wall_s": statistics.median(float(r["wall_s"]) for r in rs),  # type: ignore[arg-type]
            "median_tok_per_s": statistics.median(float(r["tok_per_s"] or 0) for r in rs),  # type: ignore[arg-type]
            "prompt_tokens": rs[0]["prompt_tokens"],
            "json_valid": f"{sum(1 for r in rs if r['json_ok'])}/{len(rs)}",
        }
    return {
        "model": model,
        "first_load_s": first["load_s"],
        "size_vram_bytes": info.get("size_vram"),
        "size_total_bytes": info.get("size"),
        "gpu_mem_before_mib": base_vram,
        "gpu_mem_loaded_mib": vram,
        "by_context": summary,
        "errors": sum(1 for r in runs if r["json_ok"] is False),
    }


def main(models: list[str]) -> None:
    results = [bench(m) for m in models]
    lines = [
        "# Local LLM hardware report",
        "",
        "Machine: NVIDIA GeForce RTX 5060 Laptop GPU (8 GB VRAM), 31 GB RAM, Ollama, one model loaded at a time.",
        f"Generated by `backend/scripts/bench_ollama.py` on {time.strftime('%Y-%m-%d %H:%M')}.",
        "Each context size: 3 runs, JSON-schema output, 160 generated tokens max, `think: false`.",
        "",
        "| Model | Load (s) | Loaded size | In VRAM | Context | Prompt tokens | Median latency (s) | Median tok/s | Valid JSON |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        size = r["size_total_bytes"] or 0
        vram = r["size_vram_bytes"] or 0
        for ctx, s in r["by_context"].items():  # type: ignore[attr-defined]
            lines.append(
                f"| {r['model']} | {r['first_load_s']} | {int(size) / 1e9:.1f} GB | "  # type: ignore[call-overload]
                f"{100 * int(vram) / max(int(size), 1):.0f}% | {ctx} | {s['prompt_tokens']} | "  # type: ignore[call-overload]
                f"{s['median_wall_s']} | {s['median_tok_per_s']} | {s['json_valid']} |"
            )
    lines += ["", "Raw results:", "", "```json", json.dumps(results, indent=1), "```", ""]
    out = REPO / "docs" / "hardware_report.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:14 + 3 * len(results)]))


if __name__ == "__main__":
    main(sys.argv[1:] or ["qwen3:8b", "llama3.1:8b"])
